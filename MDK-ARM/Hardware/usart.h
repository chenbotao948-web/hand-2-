// -------------------- PID 调参 --------------------
// Kp=40          设置比例参数 Kp，范围 0~1000，支持小数
// Ki=0.1         设置积分参数 Ki，范围 0~1000，支持小数
// Kd=5           设置微分参数 Kd，范围 0~1000，支持小数
// Base=80        设置基础速度偏移量，范围 0~250，支持小数
// PID?           查询当前 PID 参数、基础速度和循迹状态
//
// 小数示例：
// Kp=42.5
// Ki=0.05
// Kd=8.25
// Base=100.5
//
// PID? 回复示例：
// PID Kp=42.500 Ki=0.050 Kd=8.250 Base=100.500 Track=1
//
// 注意：
// 修改 Kp、Ki、Kd 会清除之前的积分和微分历史。
// 修改 Base 不会清除积分和微分历史。

// -------------------- 循迹控制 --------------------
// Track=1        启动 PID 循迹
// Track=0        停止 PID 循迹，并让两侧电机停止
//
// 成功回复示例：
// Track=1 OK

// -------------------- 红外数据显示 --------------------
// IR=1           开启红外状态变化回报
// IR=0           关闭红外状态回报
//
// 红外状态改变时输出示例：
// IR: 0xE7 11100111
//
// 调 PID 时建议先发送：
// IR=0

// -------------------- 手动控制电机 --------------------
// 手动控制前必须先停止循迹：
// Track=0
//
// LeftSpeed=1500   设置左侧电机原始 Tsig
// RightSpeed=1500  设置右侧电机原始 Tsig
